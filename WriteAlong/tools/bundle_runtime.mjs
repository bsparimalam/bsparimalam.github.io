import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();

const result = await esbuild.build({
  entryPoints: [path.join(root, 'runtime/read-entry.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  loader: { '.css': 'text' },
  write: false,
});

const bundleCode = result.outputFiles[0].text;
const bundlePath = path.join(root, 'runtime/read-bundle.js');
fs.writeFileSync(bundlePath, bundleCode);

// Also emit a small ESM helper in runtime/read-html-builder.js so the Editor can
// synthesize a complete self-contained read.html on Save / Export without network.
const escapedBundle = JSON.stringify(bundleCode);
const builderCode = `// Auto-generated by tools/bundle_runtime.mjs — do not edit by hand
export const WA_VERSION = ${JSON.stringify(version)};
const READ_BUNDLE = ${escapedBundle};

function escapeScriptText(text) {
  return String(text || '').replace(/<\\/script/gi, '<\\\\/script');
}

export function buildReadHtml({ title = 'Write Along Document', content = '', style = '', fontsBase = '' } = {}) {
  const safeTitle = String(title).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const fontsMeta = fontsBase ? \`\\n  <meta name="wa-fonts-base" content="\${fontsBase}">\` : '';
  return \`<!DOCTYPE html>
<!-- Generated by Write Along v\${WA_VERSION} -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="wa-version" content="\${WA_VERSION}">
  <meta name="generator" content="Write Along \${WA_VERSION}">\${fontsMeta}
  <link rel="icon" href="data:,">
  <title>\${safeTitle}</title>
</head>
<body>
  <div id="wa-root"></div>
  <script type="text/plain" id="wa-content">\${escapeScriptText(content)}</script>
  <script type="text/plain" id="wa-style">\${escapeScriptText(style)}</script>
  <script>\${READ_BUNDLE.replace(/<\\/script/gi, '<\\\\/script')}</script>
</body>
</html>
\`;
}
`;

fs.writeFileSync(path.join(root, 'runtime/read-html-builder.js'), builderCode);
console.log(`runtime/read-bundle.js: ${(bundleCode.length / 1024).toFixed(1)} KB`);
