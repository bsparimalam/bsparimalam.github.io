#!/usr/bin/env python3
"""
Generate all 110 .wa template directories + docs/syntax.wa + templates/index.json.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from archetypes import render_style_css
from content_library import build_content_md
from specs import TEMPLATES
from svg_art import generate_svg_figure


def load_version() -> str:
    with open(os.path.join(ROOT, "VERSION"), "r", encoding="utf-8") as f:
        return f.read().strip()


def load_read_bundle() -> str:
    path = os.path.join(ROOT, "runtime", "read-bundle.js")
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def load_canonical_syntax() -> str:
    path = os.path.join(ROOT, "docs", "syntax.md")
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def escape_script(text: str) -> str:
    return re.sub(r"</script", r"<\/script", text, flags=re.IGNORECASE)


def build_read_html(title: str, content_md: str, style_css: str, bundle_js: str, version: str, fonts_base: str) -> str:
    safe_title = title.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return f"""<!DOCTYPE html>
<!-- Generated by Write Along v{version} -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="wa-version" content="{version}">
  <meta name="generator" content="Write Along {version}">
  <meta name="wa-fonts-base" content="{fonts_base}">
  <link rel="icon" href="data:,">
  <title>{safe_title}</title>
</head>
<body>
  <div id="wa-root"></div>
  <script type="text/plain" id="wa-content">{escape_script(content_md)}</script>
  <script type="text/plain" id="wa-style">{escape_script(style_css)}</script>
  <script>{escape_script(bundle_js)}</script>
</body>
</html>
"""


def build_template_syntax(canonical: str, spec: dict, style_css: str) -> str:
    var_rows = []
    for m in re.finditer(r"(--[a-z0-9-]+)\s*:\s*([^;{}]+);", style_css, re.IGNORECASE):
        var_rows.append(f"| `{m.group(1)}` | `{m.group(2).strip()}` |")
    extra = f"""

---

## Template Reference: {spec["name"]}

- **Template ID**: `{spec["id"]}`
- **Category**: {spec["category"]}
- **Archetype**: `{spec["archetype"]}`
- **Page Size**: `{spec.get("page_size", "Letter")}`
- **Columns**: `{spec.get("columns", 1)}`
- **Fonts**: Body `{spec["fonts"]["body"]}`, Heading `{spec["fonts"]["heading"]}`, Code `{spec["fonts"].get("code", "JetBrains Mono")}`

### Active `:root` Variables

| Variable | Value |
|---|---|
{chr(10).join(var_rows)}
"""
    return canonical.rstrip() + extra


def main():
    version = load_version()
    bundle_js = load_read_bundle()
    canonical_syntax = load_canonical_syntax()

    templates_dir = os.path.join(ROOT, "templates")
    os.makedirs(templates_dir, exist_ok=True)

    seen_ids = set()
    index_entries = []

    for spec in TEMPLATES:
        tid = spec["id"]
        if tid in seen_ids:
            raise ValueError(f"Duplicate template id: {tid}")
        seen_ids.add(tid)

        tdir = os.path.join(templates_dir, f"{tid}.wa")
        img_dir = os.path.join(tdir, "images")
        os.makedirs(img_dir, exist_ok=True)

        content_md = build_content_md(spec)
        style_css = render_style_css(spec)
        svg_fig = generate_svg_figure(tid, spec["category"], spec["palette"], spec["name"])
        title = spec.get("meta", {}).get("title", spec["name"])
        read_html = build_read_html(title, content_md, style_css, bundle_js, version, "../../runtime/fonts/")
        syntax_md = build_template_syntax(canonical_syntax, spec, style_css)

        with open(os.path.join(tdir, "content.md"), "w", encoding="utf-8") as f:
            f.write(content_md)
        with open(os.path.join(tdir, "style.css"), "w", encoding="utf-8") as f:
            f.write(style_css)
        with open(os.path.join(img_dir, "figure-1.svg"), "w", encoding="utf-8") as f:
            f.write(svg_fig)
        with open(os.path.join(tdir, "read.html"), "w", encoding="utf-8") as f:
            f.write(read_html)
        with open(os.path.join(tdir, "syntax.md"), "w", encoding="utf-8") as f:
            f.write(syntax_md)

        pal = spec["palette"]
        fonts_list = list(dict.fromkeys([spec["fonts"]["heading"], spec["fonts"]["body"]]))
        index_entries.append({
            "id": tid,
            "name": spec["name"],
            "category": spec["category"],
            "archetype": spec["archetype"],
            "pageSize": spec.get("page_size", "Letter"),
            "columns": spec.get("columns", 1),
            "fonts": fonts_list,
            "palette": [pal["bg"], pal["accent"], pal["text"]],
            "tags": spec.get("tags", []),
            "images": ["images/figure-1.svg"],
            "thumbnail": "thumb.png",
        })

    # Write templates/index.json
    index_path = os.path.join(templates_dir, "index.json")
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump(
            {"version": version, "count": len(index_entries), "templates": index_entries},
            f,
            indent=2,
        )
        f.write("\n")

    # Build docs/syntax.wa/ (the canonical Syntax Guide as a live .wa document)
    guide_dir = os.path.join(ROOT, "docs", "syntax.wa")
    guide_md = canonical_syntax.replace(
        "```markdown\n![Figure 1: Modular page geometry and typographic rhythm.](images/diagram.svg)\n```",
        "```markdown\n![Figure 1: Modular page geometry and typographic rhythm.](images/diagram.svg)\n```\n\n![Figure 1: Write Along single shared renderer architecture.](images/diagram.svg)",
    )
    with open(os.path.join(guide_dir, "content.md"), "w", encoding="utf-8") as f:
        f.write(guide_md)
    with open(os.path.join(guide_dir, "style.css"), "r", encoding="utf-8") as f:
        guide_css = f.read()
    guide_read_html = build_read_html(
        "Write Along Syntax & Template Guide",
        guide_md,
        guide_css,
        bundle_js,
        version,
        "../../runtime/fonts/",
    )
    with open(os.path.join(guide_dir, "read.html"), "w", encoding="utf-8") as f:
        f.write(guide_read_html)
    with open(os.path.join(guide_dir, "syntax.md"), "w", encoding="utf-8") as f:
        f.write(canonical_syntax)

    print(f"Generated {len(index_entries)} templates in templates/ + docs/syntax.wa/ (v{version})")


if __name__ == "__main__":
    main()
