#!/usr/bin/env python3
"""
Build script:
1. Reads VERSION
2. Generates PWA manifest.webmanifest
3. Generates sw.js with versioned precache (wa-<VERSION>) covering the shell,
   runtime/, vendor/, bundled fonts, docs/syntax.wa/, and templates/index.json,
   plus background caching of templates on first load.
4. Generates contact sheets from templates/*.wa/thumb.png using Pillow.
"""
import json
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_version() -> str:
    with open(os.path.join(ROOT, "VERSION"), "r", encoding="utf-8") as f:
        return f.read().strip()


def write_manifest(version: str):
    manifest = {
        "name": "Write Along",
        "short_name": "Write Along",
        "description": "A Markdown word processor with 110+ LaTeX-quality CSS templates and print-identical preview.",
        "start_url": "./index.html",
        "scope": "./",
        "display": "standalone",
        "background_color": "#12151c",
        "theme_color": "#1e2433",
        "version": version,
        "icons": [
            {"src": "./app/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any maskable"},
            {"src": "./app/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"},
            {"src": "./app/icon.svg", "sizes": "any", "type": "image/svg+xml"},
        ],
    }
    with open(os.path.join(ROOT, "manifest.webmanifest"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")


def collect_precache_urls() -> list[str]:
    urls = [
        "./",
        "./index.html",
        "./manifest.webmanifest",
        "./VERSION",
        "./app/app.css",
        "./app/main.js",
        "./app/state.js",
        "./app/fs.js",
        "./app/editor.js",
        "./app/toolbar.js",
        "./app/preview.js",
        "./app/templates.js",
        "./app/export.js",
        "./app/theme.js",
        "./app/page-setup.js",
        "./app/logo.svg",
        "./app/icon.svg",
        "./app/icon-192.png",
        "./app/icon-512.png",
        "./runtime/render.js",
        "./runtime/paginate.js",
        "./runtime/base.css",
        "./runtime/read-html-builder.js",
        "./vendor/marked.esm.js",
        "./vendor/dompurify.esm.js",
        "./vendor/fflate.esm.js",
        "./vendor/codemirror.esm.js",
        "./docs/syntax.md",
        "./docs/syntax.wa/content.md",
        "./docs/syntax.wa/style.css",
        "./docs/syntax.wa/images/diagram.svg",
        "./templates/index.json",
    ]
    fonts_dir = os.path.join(ROOT, "runtime", "fonts")
    if os.path.isdir(fonts_dir):
        for fn in sorted(os.listdir(fonts_dir)):
            if fn.endswith(".woff2") or fn in ("fonts.css", "manifest.json"):
                urls.append(f"./runtime/fonts/{fn}")
    return urls


def write_service_worker(version: str):
    precache_urls = collect_precache_urls()
    sw_code = f"""/* Write Along Service Worker — Auto-generated by tools/build.py (v{version}) */
const WA_VERSION = {json.dumps(version)};
const CACHE_NAME = `wa-${{WA_VERSION}}`;

const PRECACHE_URLS = {json.dumps(precache_urls, indent=2)};

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  );
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((k) => k.startsWith('wa-') && k !== CACHE_NAME)
          .map((k) => caches.delete(k))
      )
    ).then(() => self.clients.claim()).then(() => warmTemplateCache())
  );
}});

self.addEventListener('message', (event) => {{
  if (event.data && event.data.type === 'SKIP_WAITING') {{
    self.skipWaiting();
  }}
}});

async function warmTemplateCache() {{
  try {{
    const cache = await caches.open(CACHE_NAME);
    const res = await cache.match('./templates/index.json') || await fetch('./templates/index.json');
    if (!res || !res.ok) return;
    const data = await res.json();
    const templates = data.templates || [];
    // Cache core template files (content.md, style.css, thumb.png, images) in polite batches
    const batchSize = 8;
    for (let i = 0; i < templates.length; i += batchSize) {{
      if (self.navigator && self.navigator.onLine === false) break;
      const slice = templates.slice(i, i + batchSize);
      const urls = [];
      for (const t of slice) {{
        const base = `./templates/${{t.id}}.wa/`;
        urls.push(`${{base}}content.md`, `${{base}}style.css`);
        if (t.thumbnail) urls.push(`${{base}}${{t.thumbnail}}`);
        for (const im of (t.images || [])) urls.push(`${{base}}${{im}}`);
      }}
      await Promise.allSettled(
        urls.map(async (u) => {{
          const hit = await cache.match(u);
          if (!hit) {{
            const fetched = await fetch(u);
            if (fetched.ok) await cache.put(u, fetched);
          }}
        }})
      );
    }}
  }} catch (_err) {{
    // Offline during background warm-up; skip silently
  }}
}}

// Cache-first strategy: assets load from server only on first load or when WA_VERSION updates.
self.addEventListener('fetch', (event) => {{
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => {{
      if (cached) return cached;
      return fetch(event.request).then((response) => {{
        if (response && response.ok && response.type === 'basic') {{
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }}
        return response;
      }});
    }})
  );
}});
"""
    with open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8") as f:
        f.write(sw_code)
    print(f"Wrote manifest.webmanifest and sw.js (cache={f'wa-{version}'}, precache={len(precache_urls)} files)")


def build_contact_sheets():
    idx_path = os.path.join(ROOT, "templates", "index.json")
    if not os.path.isfile(idx_path):
        return
    with open(idx_path, "r", encoding="utf-8") as f:
        templates = json.load(f).get("templates", [])

    thumbs = []
    for t in templates:
        p = os.path.join(ROOT, "templates", f"{t['id']}.wa", "thumb.png")
        if os.path.isfile(p):
            thumbs.append((t["name"], t["category"], p))

    if not thumbs:
        return

    cols, rows = 6, 5
    per_sheet = cols * rows
    cell_w, cell_h = 220, 300
    pad = 16
    tests_dir = os.path.join(ROOT, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    for sheet_idx in range(0, len(thumbs), per_sheet):
        chunk = thumbs[sheet_idx : sheet_idx + per_sheet]
        sheet_w = cols * (cell_w + pad) + pad
        sheet_h = rows * (cell_h + pad) + pad
        canvas = Image.new("RGB", (sheet_w, sheet_h), (235, 238, 243))
        draw = ImageDraw.Draw(canvas)

        for idx, (name, cat, p) in enumerate(chunk):
            r, c = divmod(idx, cols)
            x = pad + c * (cell_w + pad)
            y = pad + r * (cell_h + pad)
            img = Image.open(p).convert("RGB")
            img.thumbnail((cell_w - 8, cell_h - 34))
            draw.rectangle([x, y, x + cell_w, y + cell_h], fill=(255, 255, 255), outline=(205, 212, 222))
            ix = x + (cell_w - img.width) // 2
            canvas.paste(img, (ix, y + 6))
            draw.text((x + 8, y + cell_h - 24), name[:28], fill=(24, 32, 44))

        out_path = os.path.join(tests_dir, f"contact-sheet-{(sheet_idx // per_sheet) + 1}.png")
        canvas.save(out_path)
    print(f"Built {(len(thumbs) + per_sheet - 1) // per_sheet} contact sheets in tests/")


def main():
    version = load_version()
    write_manifest(version)
    write_service_worker(version)
    build_contact_sheets()


if __name__ == "__main__":
    main()
